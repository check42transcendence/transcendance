import {
  Injectable,
  Inject,
  BadRequestException,
  NotFoundException,
  ForbiddenException,
  ConflictException,
  ServiceUnavailableException,
} from '@nestjs/common';
import { CreateTripDto } from './dto/create-trip.dto.js';
import { CreateInvitationDto } from './dto/create-invitation.dto.js';
import { PrismaService } from '../database/prisma.service.js';
import { UsersRepository } from '../users/users.repository.js';
import { RealtimeService } from '../realtime/realtime.service.js';
import type {
  TripListResponse,
  TripResponse,
  TripDaysResponse,
  TripMembersResponse,
  PendingInvitationsResponse,
  MembershipResult,
} from '@tripcollab/shared';

// Limit the number of days generated by one trip creation.
const MAX_TRIP_DAYS = 365;

// Identify only the partial unique-index conflict for pending invitations.
function isPendingInvitationUniqueConflict(error: unknown): boolean {
  if (typeof error !== 'object' || error === null) {
    return false;
  }

  const failure = error as {
    code?: string;
    meta?: {
      driverAdapterError?: {
        cause?: {
          constraint?: { index?: string };
          originalMessage?: string;
        };
      };
    };
  };

  const cause = failure.meta?.driverAdapterError?.cause;
  const indexName = 'trip_invitation_one_pending_per_trip_invitee';

  return (
    failure.code === 'P2002' &&
    (cause?.constraint?.index === indexName ||
      (cause?.originalMessage ?? '').includes(indexName))
  );
}

@Injectable()
export class TripsService {
  constructor(
    @Inject(PrismaService)
    private readonly prisma: PrismaService,
    @Inject(UsersRepository)
    private readonly usersRepository: UsersRepository,
	private readonly realtime: RealtimeService,
  ) { }

  // Create a trip with its owner membership and all days.
  async create(
    creatorId: string,
    input: CreateTripDto
  ): Promise<TripResponse> {
    if (input.endDate < input.startDate) {
      throw new BadRequestException(
        'End date must not be earlier than start date',
      );
    }

    // Use UTC midnight to avoid local time-zone and daylight-saving shifts.
    const startDate = new Date(`${input.startDate}T00:00:00.000Z`);
    const endDate = new Date(`${input.endDate}T00:00:00.000Z`);
    const millisecondsPerDay = 24 * 60 * 60 * 1000;
    const dayCount =
      (endDate.getTime() - startDate.getTime()) / millisecondsPerDay + 1;

    // Reject oversized trips before allocating days or writing to the database.
    if (dayCount > MAX_TRIP_DAYS) {
      throw new BadRequestException(
        `Trip duration must not exceed ${MAX_TRIP_DAYS} days`,
      );
    }

    // Build one day entry for each date in the trip.
    const days: { dayNumber: number; date: Date }[] = [];
    for (let index = 0; index < dayCount; index++) {
      const day = new Date(startDate.getTime() + index * millisecondsPerDay);

      days.push({
        dayNumber: index + 1,
        date: day,
      });
    }

    // Save the trip, owner membership, and days atomically.
    const trip = await this.prisma.trip.create({
      data: {
        title: input.title,
        destination: input.destination,
        description: input.description ?? null,
        startDate,
        endDate,
        createdBy: creatorId,
        members: {
          create: {
            userId: creatorId,
            role: 'OWNER',
          },
        },
        days: {
          create: days,
        },
      },
      include: {
        creator: {
          select: {
            id: true,
            username: true,
          },
        },
      },
    });

    // Return the public trip detail in the API format.
    return {
      trip: {
        id: trip.id,
        title: trip.title,
        destination: trip.destination,
        description: trip.description,
        startDate: trip.startDate.toISOString().slice(0, 10),
        endDate: trip.endDate.toISOString().slice(0, 10),
        currentUserRole: 'OWNER',
        createdBy: {
          id: trip.creator.id,
          username: trip.creator.username,
        },
        createdAt: trip.createdAt.toISOString(),
      },
    };
  }

  // Find trips where the user has a current membership.
  async findAll(userId: string): Promise<TripListResponse> {
    const trips = await this.prisma.trip.findMany({
      // Show newest trips first, with a stable order for equal timestamps.
      orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
      where: {
        members: {
          some: {
            userId: userId,
          },
        },
      },
      include: {
        members: {
          where: {
            userId: userId,
          },
          select: {
            role: true,
          },
        },
      },
    });

    // Convert database records to public trip summaries.
    return {
      trips: trips.map((trip) => {
        return {
          id: trip.id,
          title: trip.title,
          destination: trip.destination,
          description: trip.description,
          startDate: trip.startDate.toISOString().slice(0, 10),
          endDate: trip.endDate.toISOString().slice(0, 10),
          currentUserRole: trip.members[0].role,
        };
      }),
    };
  }

  // Return trip details only to a current member.
  async findOne(
    userId: string,
    tripId: string
  ): Promise<TripResponse> {
    const trip = await this.prisma.trip.findFirst({
      where: {
        id: tripId,
        members: {
          some: {
            userId: userId,
          },
        },
      },
      include: {
        creator: {
          select: {
            id: true,
            username: true,
          },
        },
        members: {
          where: {
            userId: userId,
          },
          select: {
            role: true,
          },
        },
      },
    });

    // Do not reveal whether an inaccessible trip exists.
    if (!trip) {
      throw new NotFoundException({
        error: {
          code: 'TRIP_NOT_FOUND',
          message: 'Trip not found',
          details: {},
        },
      });
    }

    // Return the public detail with the caller's actual role.
    return {
      trip: {
        id: trip.id,
        title: trip.title,
        destination: trip.destination,
        description: trip.description,
        startDate: trip.startDate.toISOString().slice(0, 10),
        endDate: trip.endDate.toISOString().slice(0, 10),
        createdBy: {
          id: trip.creator.id,
          username: trip.creator.username,
        },
        createdAt: trip.createdAt.toISOString(),
        currentUserRole: trip.members[0].role,
      },
    };
  }

  // Return itinerary days only to a current member.
  async findDays(
    userId: string,
    tripId: string
  ): Promise<TripDaysResponse> {
    const trip = await this.prisma.trip.findFirst({
      where: {
        id: tripId,
        members: {
          some: {
            userId: userId,
          },
        },
      },
      select: {
        days: {
          orderBy: {
            dayNumber: 'asc',
          },
          select: {
            id: true,
            tripId: true,
            dayNumber: true,
            date: true,
          },
        },
      },
    });

    if (!trip) {
      throw new NotFoundException({
        error: {
          code: 'TRIP_NOT_FOUND',
          message: 'Trip not found',
          details: {},
        },
      });
    }

    // Convert day dates to the API's YYYY-MM-DD format.
    return {
      days: trip.days.map((day) => {
        return {
          id: day.id,
          tripId: day.tripId,
          dayNumber: day.dayNumber,
          date: day.date.toISOString().slice(0, 10),
        };
      }),
    };
  }

  // Return all current members only to a current trip participant.
  async findMembers(
    userId: string,
    tripId: string,
  ): Promise<TripMembersResponse> {
    const trip = await this.prisma.trip.findFirst({
      where: {
        id: tripId,
        members: {
          some: {
            userId: userId,
          },
        },
      },
      select: {
        members: {
          orderBy: [{ joinedAt: 'asc' }, { userId: 'asc' }],
          select: {
            role: true,
            joinedAt: true,
            user: {
              select: {
                id: true,
                username: true,
              },
            },
          },
        },
      },
    });

    // Do not reveal whether an inaccessible trip exists.
    if (!trip) {
      throw new NotFoundException({
        error: {
          code: 'TRIP_NOT_FOUND',
          message: 'Trip not found',
          details: {},
        },
      });
    }

    // Return only public member information.
    return {
      members: trip.members.map((member) => ({
        user: {
          id: member.user.id,
          username: member.user.username,
        },
        role: member.role,
        joinedAt: member.joinedAt.toISOString(),
      })),
    };
  }
  // Create a pending invitation for a registered user.
  async createInvitation(
    userId: string,
    tripId: string,
    input: CreateInvitationDto,
  ) {
    // Exactly one identifier must be provided.
    const hasUsername = input.username !== undefined;
    const hasEmail = input.email !== undefined;

    if (hasUsername === hasEmail) {
      throw new BadRequestException({
        error: {
          code: 'VALIDATION_ERROR',
          message: 'Invalid request input',
          details: {},
        },
      });
    }

    // Check permission before looking up the invitee.
    const membership = await this.prisma.tripMember.findFirst({
      where: { tripId, userId },
      select: { role: true },
    });

    if (!membership) {
      throw new NotFoundException({
        error: {
          code: 'TRIP_NOT_FOUND',
          message: 'Trip not found',
          details: {},
        },
      });
    }

    if (membership.role !== 'OWNER') {
      throw new ForbiddenException({
        error: {
          code: 'TRIP_OWNER_REQUIRED',
          message: 'Trip owner required',
          details: {},
        },
      });
    }

    // Reuse the case-insensitive account lookup rules.
    const invitee = hasUsername
      ? await this.usersRepository.findByUsername(input.username!)
      : await this.usersRepository.findByEmail(input.email!);

    if (!invitee) {
      throw new NotFoundException({
        error: {
          code: 'INVITEE_NOT_FOUND',
          message: 'Invitee not found',
          details: {},
        },
      });
    }

    try {
      return await this.prisma.$transaction(async (tx) => {
        // Lock the Trip row so deletion cannot race with invitation creation.
        const lockedTrips = await tx.$queryRaw<Array<{ id: string }>>`
          SELECT "id"
          FROM "trip"
          WHERE "id" = ${tripId}::uuid
          FOR UPDATE
        `;

        if (lockedTrips.length === 0) {
          throw new NotFoundException({
            error: {
              code: 'TRIP_NOT_FOUND',
              message: 'Trip not found',
              details: {},
            },
          });
        }

        // Recheck Owner permission while holding the Trip lock.
        const currentMembership = await tx.tripMember.findFirst({
          where: { tripId, userId },
          select: { role: true },
        });

        if (!currentMembership) {
          throw new NotFoundException({
            error: {
              code: 'TRIP_NOT_FOUND',
              message: 'Trip not found',
              details: {},
            },
          });
        }

        if (currentMembership.role !== 'OWNER') {
          throw new ForbiddenException({
            error: {
              code: 'TRIP_OWNER_REQUIRED',
              message: 'Trip owner required',
              details: {},
            },
          });
        }

        // A current member cannot receive another invitation.
        const existingMembership = await tx.tripMember.findFirst({
          where: { tripId, userId: invitee.id },
          select: { userId: true },
        });

        if (existingMembership) {
          throw new ConflictException({
            error: {
              code: 'MEMBERSHIP_ALREADY_EXISTS',
              message: 'User is already a trip member',
              details: {},
            },
          });
        }

        // Return a domain conflict before attempting the insert.
        const existingInvitation = await tx.tripInvitation.findFirst({
          where: {
            tripId,
            inviteeId: invitee.id,
            status: 'PENDING',
          },
          select: { id: true },
        });

        if (existingInvitation) {
          throw new ConflictException({
            error: {
              code: 'INVITATION_ALREADY_PENDING',
              message: 'Invitation is already pending',
              details: {},
            },
          });
        }

        const invitation = await tx.tripInvitation.create({
          data: {
            tripId,
            invitedBy: userId,
            inviteeId: invitee.id,
            status: 'PENDING',
          },
          select: {
            id: true,
            status: true,
            createdAt: true,
          },
        });

        return {
          invitation: {
            id: invitation.id,
            status: invitation.status,
            createdAt: invitation.createdAt.toISOString(),
          },
        };
      });
    } catch (error: unknown) {
      // The database index also protects against concurrent duplicate requests.
      if (isPendingInvitationUniqueConflict(error)) {
        throw new ConflictException({
          error: {
            code: 'INVITATION_ALREADY_PENDING',
            message: 'Invitation is already pending',
            details: {},
          },
        });
      }

      throw error;
    }
  }

  // Accept a pending invitation atomically for its intended recipient.
  async acceptInvitation(
    userId: string,
    invitationId: string,
  ): Promise<MembershipResult> {
    return this.prisma.$transaction(async (tx) => {
      // Read the Trip ID first to follow the canonical Trip-first lock order.
      const invitationReference = await tx.tripInvitation.findFirst({
        where: { id: invitationId, inviteeId: userId },
        select: { tripId: true },
      });

      if (!invitationReference) {
        throw new NotFoundException({
          error: {
            code: 'INVITATION_NOT_FOUND',
            message: 'Invitation not found',
            details: {},
          },
        });
      }

      const tripId = invitationReference.tripId;

      // Lock Trip before Invitation.
      const lockedTrips = await tx.$queryRaw<Array<{ id: string }>>`
        SELECT "id"
        FROM "trip"
        WHERE "id" = ${tripId}::uuid
        FOR UPDATE
      `;

      if (lockedTrips.length === 0) {
        throw new NotFoundException({
          error: {
            code: 'INVITATION_NOT_FOUND',
            message: 'Invitation not found',
            details: {},
          },
        });
      }

      // Lock and revalidate the invitation.
      const lockedInvitations = await tx.$queryRaw<
        Array<{ status: string }>
      >`
        SELECT "status"
        FROM "trip_invitation"
        WHERE "id" = ${invitationId}::uuid
          AND "invitee_id" = ${userId}::uuid
        FOR UPDATE
      `;

      if (lockedInvitations.length === 0) {
        throw new NotFoundException({
          error: {
            code: 'INVITATION_NOT_FOUND',
            message: 'Invitation not found',
            details: {},
          },
        });
      }

      if (lockedInvitations[0].status !== 'PENDING') {
        throw new ConflictException({
          error: {
            code: 'INVITATION_NOT_PENDING',
            message: 'Invitation is not pending',
            details: {},
          },
        });
      }

      // Prevent duplicate Membership creation.
      const existingMembership = await tx.tripMember.findUnique({
        where: {
          tripId_userId: {
            tripId,
            userId,
          },
        },
        select: { userId: true },
      });

      if (existingMembership) {
        throw new ConflictException({
          error: {
            code: 'MEMBERSHIP_ALREADY_EXISTS',
            message: 'User is already a trip member',
            details: {},
          },
        });
      }

      const membership = await tx.tripMember.create({
        data: {
          tripId,
          userId,
          role: 'MEMBER',
        },
        select: {
          joinedAt: true,
        },
      });

      await tx.tripInvitation.update({
        where: { id: invitationId },
        data: {
          status: 'ACCEPTED',
          respondedAt: new Date(),
        },
      });

      return {
        tripId,
        userId,
        role: 'MEMBER',
        joinedAt: membership.joinedAt.toISOString(),
      };
    });
  }

  // Reject a pending invitation atomically for its intended recipient.
  async rejectInvitation(
    userId: string,
    invitationId: string,
  ): Promise<void> {
    await this.prisma.$transaction(async (tx) => {
      // Read the Trip ID first to follow the canonical Trip-first lock order.
      const invitationReference = await tx.tripInvitation.findFirst({
        where: { id: invitationId, inviteeId: userId },
        select: { tripId: true },
      });

      if (!invitationReference) {
        throw new NotFoundException({
          error: {
            code: 'INVITATION_NOT_FOUND',
            message: 'Invitation not found',
            details: {},
          },
        });
      }

      const tripId = invitationReference.tripId;

      // Lock Trip before Invitation.
      const lockedTrips = await tx.$queryRaw<Array<{ id: string }>>`
        SELECT "id"
        FROM "trip"
        WHERE "id" = ${tripId}::uuid
        FOR UPDATE
      `;

      if (lockedTrips.length === 0) {
        throw new NotFoundException({
          error: {
            code: 'INVITATION_NOT_FOUND',
            message: 'Invitation not found',
            details: {},
          },
        });
      }

      // Lock and revalidate the invitation.
      const lockedInvitations = await tx.$queryRaw<
        Array<{ status: string }>
      >`
        SELECT "status"
        FROM "trip_invitation"
        WHERE "id" = ${invitationId}::uuid
          AND "invitee_id" = ${userId}::uuid
        FOR UPDATE
      `;

      if (lockedInvitations.length === 0) {
        throw new NotFoundException({
          error: {
            code: 'INVITATION_NOT_FOUND',
            message: 'Invitation not found',
            details: {},
          },
        });
      }

      if (lockedInvitations[0].status !== 'PENDING') {
        throw new ConflictException({
          error: {
            code: 'INVITATION_NOT_PENDING',
            message: 'Invitation is not pending',
            details: {},
          },
        });
      }

      await tx.tripInvitation.update({
        where: { id: invitationId },
        data: {
          status: 'REJECTED',
          respondedAt: new Date(),
        },
      });
    });
  }

  // List only pending invitations received by the authenticated user.
  async findPendingInvitations(
    userId: string,
    status: string | undefined,
  ): Promise<PendingInvitationsResponse> {
    // This endpoint currently supports only the PENDING status.
    if (status !== 'PENDING') {
      throw new BadRequestException({
        error: {
          code: 'VALIDATION_ERROR',
          message: 'Invalid request input',
          details: {},
        },
      });
    }

    const invitations = await this.prisma.tripInvitation.findMany({
      where: {
        inviteeId: userId,
        status: 'PENDING',
      },
      orderBy: [{ createdAt: 'desc' }, { id: 'desc' }],
      select: {
        id: true,
        status: true,
        createdAt: true,
        trip: {
          select: {
            id: true,
            title: true,
            destination: true,
            startDate: true,
            endDate: true,
          },
        },
        inviter: {
          select: {
            id: true,
            username: true,
          },
        },
      },
    });

    return {
      invitations: invitations.map((invitation) => ({
        id: invitation.id,
        status: 'PENDING',
        trip: {
          id: invitation.trip.id,
          title: invitation.trip.title,
          destination: invitation.trip.destination,
          startDate: invitation.trip.startDate.toISOString().slice(0, 10),
          endDate: invitation.trip.endDate.toISOString().slice(0, 10),
        },
        invitedBy: {
          id: invitation.inviter.id,
          username: invitation.inviter.username,
        },
        createdAt: invitation.createdAt.toISOString(),
      })),
    };
  }

  // Allow a current Member to leave a Trip and clean up their Votes atomically.
  async leaveTrip(userId: string, tripId: string): Promise<void> {
    await this.prisma.$transaction(async (tx) => {
      // Lock the Trip before checking or changing Membership.
      const lockedTrips = await tx.$queryRaw<Array<{ id: string }>>`
        SELECT "id"
        FROM "trip"
        WHERE "id" = ${tripId}::uuid
        FOR UPDATE
      `;

      if (lockedTrips.length === 0) {
        throw new NotFoundException({
          error: {
            code: 'TRIP_NOT_FOUND',
            message: 'Trip not found',
            details: {},
          },
        });
      }

      // Lock the caller's Membership while holding the Trip lock.
      const memberships = await tx.$queryRaw<Array<{ role: string }>>`
        SELECT "role"
        FROM "trip_member"
        WHERE "trip_id" = ${tripId}::uuid
          AND "user_id" = ${userId}::uuid
        FOR UPDATE
      `;

      if (memberships.length === 0) {
        throw new NotFoundException({
          error: {
            code: 'TRIP_NOT_FOUND',
            message: 'Trip not found',
            details: {},
          },
        });
      }

      if (memberships[0].role === 'OWNER') {
        throw new ConflictException({
          error: {
            code: 'OWNER_CANNOT_LEAVE',
            message: 'Trip owner cannot leave',
            details: {},
          },
        });
      }

      // Remove only this user's Votes belonging to this Trip.
      await tx.proposalVote.deleteMany({
        where: {
          userId,
          proposal: { tripId },
        },
      });

      // Remove the Membership after cleaning up the user's Votes.
      const result = await tx.tripMember.deleteMany({
        where: {
          tripId,
          userId,
          role: 'MEMBER',
        },
      });

      if (result.count !== 1) {
        throw new NotFoundException({
          error: {
            code: 'TRIP_NOT_FOUND',
            message: 'Trip not found',
            details: {},
          },
        });
      }

      // Complete Socket eviction before allowing the database transaction to commit.
      try {
        await this.realtime.removeUserFromTrip(userId, tripId);
      } catch {
        throw new ServiceUnavailableException({
          error: {
            code: 'TRIP_SOCKET_CLEANUP_FAILED',
            message: 'Unable to remove active Trip subscriptions. Please retry.',
            details: {},
          },
        });
      }
    });
  }

  // Allow only the current owner to proceed with trip deletion.
  async remove(
    userId: string,
    tripId: string
  ): Promise<void> {
    const membership = await this.prisma.tripMember.findFirst({
      where: {
        tripId: tripId,
        userId: userId,
      },
      select: {
        role: true,
      },
    });

    if (!membership) {
      throw new NotFoundException({
        error: {
          code: 'TRIP_NOT_FOUND',
          message: 'Trip not found',
          details: {},
        },
      });
    }

    if (membership.role !== 'OWNER') {
      throw new ForbiddenException({
        error: {
          code: 'TRIP_OWNER_REQUIRED',
          message: 'Trip owner required',
          details: {},
        },
      });
    }

    // Delete only while the caller still has an owner membership.
    const deleteResult = await this.prisma.trip.deleteMany({
      where: {
        id: tripId,
        members: {
          some: {
            userId: userId,
            role: 'OWNER',
          },
        },
      },
    });

    if (deleteResult.count === 0) {
      throw new NotFoundException({
        error: {
          code: 'TRIP_NOT_FOUND',
          message: 'Trip not found',
          details: {},
        },
      });
    }
	await this.realtime.removeTripRoom(tripId);
  }
}
